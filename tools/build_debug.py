#!/usr/bin/env python3
"""
build_debug.py -- the DEBUG PAGE: the built faithful page plus the debug layer (web/debug.js).

    python tools/build_debug.py

Runs tools/build.py first, so the faithful page is built from the current sources, then writes
web/<name>_debug.html (port.json's `out` with `_debug` before the extension): the faithful page with

  - its first line, the GENERATED banner, replaced by one naming this script and both sources;
  - its <title> suffixed " (debug)";
  - web/debug.js inlined at the END of the page's script -- after the page's own code and its __PORT__ hook, so the
    layer sees the page's `game` and the engine's classes -- between begin / end markers.

THE BOUNDARY (house rule 5: the faithful path untouched, the added layer declared), checked before anything is written:
  - the faithful page must not carry the layer's marker (BB_DBG): the layer is never in the page a player gets;
  - the debug page, with the layer cut out between its markers, the title's suffix dropped and the faithful banner put
    back, IS the faithful page, byte for byte.
The debug page holds the same tape-derived assets as the faithful one, so it is git-ignored the same way (rule 7).
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MARK = 'BB_DBG'
LAYER = 'web/debug.js'
SUFFIX = ' (debug)'


def fail(msg):
    sys.exit('BUILD_DEBUG FAILED: ' + msg)


def assemble(page, layer, out_rel):
    """The debug page from the faithful page's text and the layer's -- and THE BOUNDARY checked on the result.  Fails
    (SystemExit) rather than return a page that is not the faithful page plus the layer."""
    nl = '\r\n' if '\r\n' in page else '\n'
    layer = layer.replace('\r\n', '\n').replace('\n', nl).rstrip('\r\n')
    if MARK in page:
        fail('the faithful page %s carries %s -- the debug layer must never be in it' % (out_rel, MARK))
    if MARK not in layer:
        fail('%s does not carry its marker %s' % (LAYER, MARK))

    first = page.index(nl) + len(nl)                     # the GENERATED banner is the first line
    if not page.startswith('<!-- GENERATED'):
        fail('the faithful page does not begin with its GENERATED banner')
    tj = page.find('</title>')
    if page.count('</title>') != 1 or tj < first:
        fail('the faithful page has not exactly one <title>')
    sj = page.rfind('</script>')
    if sj < 0 or page[sj:].strip() != '</script>':
        fail('the faithful page does not end with its script')
    begin = '/* ---- begin %s -- appended by tools/build_debug.py: THE DEBUG LAYER, not in the faithful page ---- */' % LAYER
    end = '/* ---- end %s ---- */' % LAYER
    banner = ('<!-- GENERATED by tools/build_debug.py from %s + %s -- THE DEBUG PAGE, not the faithful one. '
              'DO NOT EDIT THIS FILE. -->' % (out_rel, LAYER))
    dbg = (banner + nl + page[first:tj] + SUFFIX + page[tj:sj] +
           begin + nl + layer + nl + end + nl + page[sj:])

    # THE BOUNDARY, read back off the OUTPUT by its markers
    i, j = dbg.find(begin), dbg.find(end)
    if dbg.count(begin) != 1 or dbg.count(end) != 1 or j < i:
        fail('the layer\'s markers are not one pair')
    back = dbg[:i] + dbg[j + len(end) + len(nl):]
    if back.count(SUFFIX + '</title>') != 1:
        fail('the title\'s suffix is not once')
    back = back.replace(SUFFIX + '</title>', '</title>', 1)
    back = page[:first] + back[back.index(nl) + len(nl):]
    if back != page:
        fail('the debug page is not the faithful page plus the layer')
    if dbg[i:j].count(MARK) != dbg.count(MARK):
        fail('the marker %s appears outside the layer' % MARK)
    return dbg


def paths():
    """port.json's faithful page and the debug page beside it, repo-relative"""
    cfg = json.load(open(os.path.join(ROOT, 'port.json'), encoding='utf-8'))
    out_rel = cfg.get('out') or ('web/%s.html' % cfg.get('name', 'game'))
    base, ext = os.path.splitext(out_rel)
    return out_rel, base + '_debug' + ext


def main():
    r = subprocess.run([sys.executable, os.path.join(HERE, 'build.py')], cwd=ROOT)
    if r.returncode:
        fail('tools/build.py failed')
    out_rel, dbg_rel = paths()
    page = open(os.path.join(ROOT, out_rel), 'rb').read().decode('utf-8')
    layer = open(os.path.join(ROOT, LAYER), 'rb').read().decode('utf-8')
    dbg = assemble(page, layer, out_rel)
    open(os.path.join(ROOT, dbg_rel), 'wb').write(dbg.encode('utf-8'))
    print('wrote %s (%d bytes): %s + %s (%d bytes) -- the faithful page read back from it byte for byte'
          % (dbg_rel, len(dbg.encode('utf-8')), out_rel, LAYER, len(layer.encode('utf-8'))))


if __name__ == '__main__':
    main()
